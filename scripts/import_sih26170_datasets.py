"""Import the legacy SIH26170 wide datasets without weakening HOPIUM safeguards."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data.adapters.sih26170 import export_converted_dataset


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        default="../SIH26170/data",
        help="Directory containing lot_10k_training.csv and nasa_real_dataset.csv.",
    )
    parser.add_argument("--output-dir", default="data/external")
    args = parser.parse_args()

    source_dir = Path(args.source_dir)
    output_dir = Path(args.output_dir)

    jobs = (
        (
            "lot_10k_training.csv",
            "sih26170_10k_converted.csv",
            "sih26170_10k_converted.meta.json",
            "sih26170_legacy_10k_converted",
            "Legacy SIH26170 10,000-component synthetic training export.",
        ),
        (
            "nasa_real_dataset.csv",
            "nasa_pcoe_derived_converted.csv",
            "nasa_pcoe_derived_converted.meta.json",
            "nasa_pcoe_derived_external_evaluation",
            (
                "SIH26170 NASA PCoE-derived baseline export. Its 24h/96h/168h trajectories "
                "were generated by the legacy script and are not observed NASA aging labels."
            ),
        ),
    )

    for source_name, csv_name, meta_name, dataset_id, description in jobs:
        source = source_dir / source_name
        if not source.exists():
            raise FileNotFoundError(f"Expected source dataset not found: {source}")
        meta = export_converted_dataset(
            source,
            output_dir / csv_name,
            output_dir / meta_name,
            dataset_id=dataset_id,
            source_description=description,
            lot_split_eligible=False,
        )
        print(
            f"Exported {csv_name}: {meta['total_rows']} rows across {meta['num_lots']} lots "
            "(not eligible for model selection)."
        )


if __name__ == "__main__":
    main()
