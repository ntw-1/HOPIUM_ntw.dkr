"""Evaluate registered Module B artifacts without retraining or model reselection.

Use ``--mode locked-blind`` only after training is complete.  Use ``--mode
external`` for descriptive, non-gating datasets such as the NASA PCoE-derived
legacy export; external results are never model-selection evidence.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.model_lab.features import build_feature_matrix
from src.model_lab.predictor import ProductionPredictor


def _metrics(y_true, y_pred) -> dict:
    return {
        "MAE": round(float(mean_absolute_error(y_true, y_pred)), 6),
        "RMSE": round(float(mean_squared_error(y_true, y_pred) ** 0.5), 6),
        "R2": round(float(r2_score(y_true, y_pred)), 6),
    }


def _markdown(report: dict) -> str:
    lines = [
        "# Registered Module B Evaluation",
        "",
        f"**Evaluation type:** `{report['evaluation_type']}`  ",
        f"**Dataset:** `{report['dataset_csv']}`  ",
        f"**Selection status:** {report['selection_status']}",
        "",
        "| Parameter | Samples | Lots | Model | MAE | RMSE | R² |",
        "| :--- | ---: | ---: | :--- | ---: | ---: | ---: |",
    ]
    for parameter, result in report["parameters"].items():
        metrics = result["metrics"]
        lines.append(
            f"| {parameter} | {result['sample_count']} | {result['lot_count']} | "
            f"{result['model_id']} | {metrics['MAE']:.6f} | {metrics['RMSE']:.6f} | {metrics['R2']:.6f} |"
        )
    lines.extend(["", "## Interpretation", "", report["interpretation"], ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/model_lab_10k_config.yaml")
    parser.add_argument("--mode", choices=("locked-blind", "external"), required=True)
    parser.add_argument("--csv", help="Required for external mode; optional for locked-blind mode.")
    parser.add_argument("--output-prefix", default=None)
    args = parser.parse_args()

    with Path(args.config).open("r", encoding="utf-8") as handle:
        cfg = yaml.safe_load(handle)["model_lab_config"]

    csv_path = Path(args.csv or cfg["dataset"]["csv_path"])
    df = pd.read_csv(csv_path)
    registry_dir = cfg["registry"]["output_dir"]

    if args.mode == "locked-blind":
        split_path = Path(cfg["split"]["split_output_path"])
        with split_path.open("r", encoding="utf-8") as handle:
            split = json.load(handle)
        lots = split["blind_lots"]
        evaluation_type = "final_locked_blind_test"
        selection_status = "Blind lots unsealed only for this final evaluation; no retraining or reselection occurred."
        interpretation = (
            "These are final held-out synthetic test metrics for the registered candidate artifacts. "
            "They are not evidence of real-world performance."
        )
    else:
        lots = sorted(df["lot_id"].unique().tolist())
        evaluation_type = "external_non_gating_check"
        selection_status = "External evaluation is descriptive only and did not influence training or model selection."
        interpretation = (
            "This dataset is NASA PCoE-derived only at its baseline-source stage; its aging trajectories "
            "and targets were generated by the legacy exporter. These metrics must not be represented as "
            "real-world accuracy or as a deployment qualification."
        )

    results = {}
    for parameter in cfg["parameters"]:
        X, y_true, _ = build_feature_matrix(df, parameter, lots)
        predictor = ProductionPredictor.from_registry(registry_dir, parameter)
        y_pred = predictor.predict(X)["predictions"]
        results[parameter] = {
            "model_id": predictor.model_id,
            "sample_count": int(len(y_true)),
            "lot_count": int(df[(df["parameter_name"] == parameter) & df["lot_id"].isin(lots)]["lot_id"].nunique()),
            "metrics": _metrics(y_true, y_pred),
        }

    report = {
        "evaluation_type": evaluation_type,
        "dataset_csv": str(csv_path).replace("\\", "/"),
        "evaluated_lots": lots,
        "selection_status": selection_status,
        "interpretation": interpretation,
        "parameters": results,
    }
    output_prefix = args.output_prefix or args.mode.replace("-", "_")
    output_dir = Path("reports/evaluation")
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / f"{output_prefix}.json"
    md_path = output_dir / f"{output_prefix}.md"
    json_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    md_path.write_text(_markdown(report), encoding="utf-8")
    print(f"Evaluation report written: {json_path}")


if __name__ == "__main__":
    main()
